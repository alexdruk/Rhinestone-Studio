await test('17. SVG export renders a StoneLayout generated by every new fill mode without error', () => {
  const engine = new GeometryEngine();
  for (const mode of ['fill', 'staggered', 'radial', 'contour']) {
    const layout = engine.generateShapeLayout({ shape: 'circle', layerId: 'c', stoneSizeMm: 2, gapMm: 0.3, mode, cxMm: 30, cyMm: 30, radiusMm: 20 });
    const svg = stoneLayoutToSvg(layout, { widthMm: 60, heightMm: 60 });
    assert.ok(svg.includes('<svg'), `expected valid SVG markup for ${mode}`);
    assert.equal((svg.match(/<circle/g) || []).length, layout.count, `expected one <circle> per stone for ${mode}`);
  }
});

await test('18. Production Sheet export renders a StoneLayout generated by every new fill mode without error, across mixed stone sizes', () => {
  const engine = new GeometryEngine();
  const layers = ['fill', 'staggered', 'radial', 'contour'].map((mode, i) =>
    engine.generateShapeLayout({ shape: 'rectangle', layerId: `r${i}`, stoneSizeMm: 1.4 + i, gapMm: 0.3, mode, xMm: i * 20, yMm: 0, widthMm: 15, heightMm: 15 })
  );
  const allStones = layers.flatMap((l) => l.stones);
  const combined = new (Object.getPrototypeOf(layers[0]).constructor)({ layerId: 'project', stones: allStones });
  const options = { projectName: 'RS-1011 Fill Modes', objectType: 'Mug', productionWidthMm: 210, productionHeightMm: 90, gapMm: [0.3] };
  const svg = productionSheetToSvg(combined, options);
  assert.ok(svg.includes('<svg'));
  const { pageWidthMm, pageHeightMm } = computeProductionSheetLayout(combined, options);
  assert.ok(pageWidthMm > 0 && pageHeightMm > 0);
});

