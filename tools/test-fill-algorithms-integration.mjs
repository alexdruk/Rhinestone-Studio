// --- 2. Every generate*StonesLive call site resolves its layer type's mode through the shared, --
//        backward-compatible resolver helpers, not a hard-coded value ---------------------------

await test('5. generateTextStonesLive resolves mode via resolveTextFillMode(layer.textMode)', () => {
  assert.match(appJs, /const mode=resolveTextFillMode\(layer\.textMode\);/);
});

await test('6. generateShapeStonesLive (circle/rectangle) resolves mode via resolveVectorFillMode(layer.fillMode) -- previously hard-coded to \'outline\'', () => {
  assert.match(appJs, /mode:resolveVectorFillMode\(layer\.fillMode\),color:layer\.color/);
});

await test('7. generateSvgStonesLive resolves mode via resolveVectorFillMode(layer.mode)', () => {
  // S-200 CI follow-up (2026-07): the approved S-200 spec intentionally extends this same params
  // object with a trailing `,...mixedSizeParamsFor(layer)` spread (forwarding Mixed Stone-Size
  // params through every generate*StonesLive() method) -- see docs/specifications/
  // S-200-MixedStoneSizeLayouts.md, "Architecture > app.js / index.html". The optional non-capturing
  // group tolerates that addition without weakening what this test actually checks: mode resolution
  // via resolveVectorFillMode(layer.mode) immediately followed by color:layer.color.
  assert.match(appJs, /mode:resolveVectorFillMode\(layer\.mode\),color:layer\.color(?:,\.\.\.mixedSizeParamsFor\(layer\))?\};const result=this\.permanentEngine\.generateSvgLayout/);
});

await test('8. generateImageStonesLive forwards mode via resolveImageFillMode(layer.fillMode) -- previously no mode was forwarded at all', () => {
  assert.match(appJs, /mode:resolveImageFillMode\(layer\.fillMode\),color:layer\.color,threshold:layer\.threshold/);
});

await test('9. generatePathStonesLive resolves mode via resolveVectorFillMode(layer.fillMode) -- previously hard-coded to \'outline\'', () => {
  // S-200 CI follow-up (2026-07): same tolerance as test 7 above, for the same reason.
  // RS-3011 (2026-08): tolerates the closed:layer.closed!==false field the open-contour fix added
  // between color and the mixedSizeParamsFor spread.
  // RS-3011 Step 10b (2026-08): tolerates the regions:layer.regions||[] field (plus its own
  // multi-line doc comment) the Paint regions-forwarding fix added between closed and
  // mixedSizeParamsFor -- the [^;]*? connectors (rather than a fixed `,fieldName` literal like the
  // closed/mixedSizeParamsFor groups use) skip over that comment/whitespace without being so loose
  // they'd span into an unrelated generate*StonesLive() method: `;` only ever appears at a
  // statement boundary, never inside this params object literal or its own comments, so a
  // connector that excludes it can't cross into a neighboring method's own params object.
  assert.match(appJs, /gapMm:layer\.gap,mode:resolveVectorFillMode\(layer\.fillMode\),color:layer\.color(?:,closed:layer\.closed!==false)?(?:[^;]*?regions:layer\.regions\|\|\[\],)?(?:[^;]*?\.\.\.mixedSizeParamsFor\(layer\))?\};const result=this\.permanentEngine\.generatePathLayout/);
});

await test('10. the resolver helpers themselves default unknown/missing values to each layer type\'s pre-RS-1011 behavior (backward compatibility)', () => {
  assert.match(appJs, /function resolveTextFillMode\(textMode\)\{return TEXT_MODE_TO_ENGINE_MODE\[textMode\]\|\|'outline'\}/);
  assert.match(appJs, /function resolveVectorFillMode\(value\)\{return VECTOR_FILL_MODES\.has\(value\)\?value:'outline'\}/);
  assert.match(appJs, /function resolveImageFillMode\(value\)\{return IMAGE_FILL_MODES\.has\(value\)\?value:'fill'\}/);
});

